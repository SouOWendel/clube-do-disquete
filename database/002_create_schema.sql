BEGIN;

-- guarda as contas dos usuarios com email e nome unicos, alem de hash de senha ou identificador Google. o aceite dos termos é obrigatorio para registrar a conta
CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR NOT NULL UNIQUE,
    nome_usuario VARCHAR NOT NULL UNIQUE,
    hash_senha VARCHAR,
    identificador_google VARCHAR UNIQUE,
    termos_aceitos BOOLEAN NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- armazena as seis categorias fixas do forum com codigo e nome unicos, pois todo topico precisa estar vinculado a uma categoria valida. a opcao todas é usada apenas como filtro na interface e nao fica salva aqui
CREATE TABLE categorias (
    id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR NOT NULL UNIQUE,
    nome VARCHAR NOT NULL UNIQUE
);

