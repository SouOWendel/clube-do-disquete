-- registra os topicos criados pelos usuarios com autor e categoria obrigatorios e limite de caracteres no titulo (de 8 a 140) e no corpo (minimo de 20), seguindo as regras de negocio da especificacao. a exclusao de autor ou categoria com topicos vinculados é bloqueada para manter o historico
CREATE TABLE topicos (
    id_topico BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_autor BIGINT NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    id_categoria INT NOT NULL REFERENCES categorias (id_categoria) ON DELETE RESTRICT,
    titulo VARCHAR(140) NOT NULL,
    corpo VARCHAR NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT topicos_titulo_limite_minimo CHECK (CHAR_LENGTH(titulo) >= 8),
    CONSTRAINT topicos_corpo_limite_minimo CHECK (CHAR_LENGTH(corpo) >= 20)
);

-- guarda as respostas vinculadas a um topico e a um autor obrigatorios, com limite maximo de 10000 caracteres no corpo conforme a especificacao. quando um topico é excluido, todas as suas respostas sao removidas em cascata
CREATE TABLE respostas (
    id_resposta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_topico BIGINT NOT NULL REFERENCES topicos (id_topico) ON DELETE CASCADE,
    id_autor BIGINT NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    corpo VARCHAR(10000) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;